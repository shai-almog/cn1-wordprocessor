#!/usr/bin/env python3
"""Regenerate the compact Unicode 16.0.0 letter/mark/digit table used on all app runtimes.

Requires Python unicodedata 16.0.0 so regeneration is deterministic.
"""
from pathlib import Path
import unicodedata
assert unicodedata.unidata_version == '16.0.0', unicodedata.unidata_version


def code(category):
    return 1 if category[0] == 'L' else 2 if category[0] == 'M' else 3 if category == 'Nd' else 0


starts, codes, previous = [], [], 0
for cp in range(0x110000):
    c = code(unicodedata.category(chr(cp)))
    if c != previous:
        starts.append(cp); codes.append(str(c)); previous = c
values = [hex(cp) for cp in starts]
lines = ['    ' + ', '.join(values[i:i + 12]) + (',' if i + 12 < len(values) else '') for i in range(0, len(values), 12)]
code_lines = ['      + "' + ''.join(codes[i:i + 80]) + '"' for i in range(0, len(codes), 80)]
code_lines[0] = '      "' + code_lines[0][9:]
source = '''package com.codenameone.wordprocessor;

/** Unicode 16.0.0 letters, marks and decimal digits.
 * Generated by scripts/generate-unicode-classes.py; do not edit the tables manually.
 * Codename One forbids Character.isLetter/isLetterOrDigit/getType because the ports'
 * category tables differ, so every runtime classifies text through these same tables.
 */
final class Unicode {
  private Unicode() {}
  private static final int LETTER = 1, MARK = 2, DIGIT = 3;
  /** Code points where the class changes; CLASSES holds the class from each start on. */
  private static final int[] STARTS = {
''' + '\n'.join(lines) + '''
  };
  private static final String CLASSES =
''' + '\n'.join(code_lines) + ''';

  private static int of(int cp) {
    int low = 0, high = STARTS.length - 1, found = -1;
    while (low <= high) {
      int middle = (low + high) >>> 1;
      if (STARTS[middle] <= cp) {
        found = middle;
        low = middle + 1;
      } else high = middle - 1;
    }
    return found < 0 ? 0 : CLASSES.charAt(found) - '0';
  }

  static boolean letter(int cp) { return of(cp) == LETTER; }

  static boolean letterOrDigit(int cp) {
    int c = of(cp);
    return c == LETTER || c == DIGIT;
  }

  static boolean mark(int cp) { return of(cp) == MARK; }

  /** Letters, marks, decimal digits and underscore: what word navigation moves over. */
  static boolean word(int cp) { return cp == '_' || of(cp) != 0; }
}
'''
root = Path(__file__).resolve().parent.parent
(root / 'common/src/main/java/com/codenameone/wordprocessor/Unicode.java').write_text(source)
print(len(starts), 'runs')
