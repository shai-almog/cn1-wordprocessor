#!/usr/bin/env python3
"""Regenerate the compact Unicode word-character table used on all app runtimes.

Requires Python unicodedata 16.0.0 so regeneration is deterministic. This is
classification for editor word movement, not UAX #29 word/grapheme segmentation.
"""
from pathlib import Path
import unicodedata
assert unicodedata.unidata_version == '16.0.0', unicodedata.unidata_version
ranges=[]
for cp in range(0x110000):
 category=unicodedata.category(chr(cp))
 if category[0] in ('L','M') or category=='Nd' or cp==95:
  if ranges and cp==ranges[-1][1]+1:ranges[-1][1]=cp
  else:ranges.append([cp,cp])
values=[hex(cp) for pair in ranges for cp in pair]
lines=['    '+', '.join(values[i:i+12])+(',' if i+12<len(values) else '') for i in range(0,len(values),12)]
source='''package com.codenameone.wordprocessor;

/** Unicode 16.0.0 letters, marks, decimal digits and underscore.
 * Generated by scripts/generate-word-ranges.py; do not edit the ranges manually.
 * ParparVM's Character category table is incomplete, so navigation uses the same
 * compact ranges on the JVM, native targets and browser.
 */
final class WordCharacters {
  private WordCharacters() {}
  private static final int[] RANGES = {
'''+ '\n'.join(lines)+'''
  };

  static boolean contains(int codePoint) {
    int low = 0, high = RANGES.length / 2 - 1;
    while (low <= high) {
      int middle = (low + high) >>> 1;
      if (codePoint < RANGES[middle * 2]) high = middle - 1;
      else if (codePoint > RANGES[middle * 2 + 1]) low = middle + 1;
      else return true;
    }
    return false;
  }
}
'''
root=Path(__file__).resolve().parent.parent
(root/'document/src/main/java/com/codenameone/wordprocessor/WordCharacters.java').write_text(source)
print(len(ranges),'ranges')
