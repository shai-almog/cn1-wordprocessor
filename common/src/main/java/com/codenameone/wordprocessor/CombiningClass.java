  /** HarfBuzz's MAX_COMBINING_MARKS: longer runs are left unsorted. */
  private static final int MAX_MARKS = 32;

  /** The canonical combining class of {@code cp}. */
  static int of(int cp) {
    int lo = 0, hi = RANGES.length / 3 - 1;
    while (lo <= hi) {
      int mid = (lo + hi) >>> 1;
      if (cp < RANGES[3 * mid]) hi = mid - 1;
      else if (cp > RANGES[3 * mid + 1]) lo = mid + 1;
      else return RANGES[3 * mid + 2];
    }
    return 0;
  }

  /** harfrust's modified combining class of {@code cp} (0 for starters). */
  static int modified(int cp) {
    // SAKOT after tone marks, PADMA after vowel marks, TSA -PHRU before U+0F74 (as harfrust).
    if (cp == 0x1a60 || cp == 0x0fc6) return 254;
    if (cp == 0x0f39) return 127;
    return MODIFIED[of(cp)];
  }

  /**
   * Stably sorts each run of marks in {@code buffer} by modified combining class, merging the
   * run's clusters (each glyph of a reordered run carries the run's whole text span).
   */
  static void reorder(List<OpenType.Glyph> buffer) {
    int n = buffer.size();
    for (int i = 0; i < n; ) {
      if (modified(buffer.get(i).cp) == 0) {
        i++;
        continue;
      }
      int end = i + 1;
      while (end < n && modified(buffer.get(end).cp) != 0) end++;
      if (end - i > 1 && end - i <= MAX_MARKS) {
        boolean moved = false;
        for (int k = i + 1; k < end; k++) {
          var g = buffer.get(k);
          int c = modified(g.cp), j = k;
          while (j > i && modified(buffer.get(j - 1).cp) > c) {
            buffer.set(j, buffer.get(j - 1));
            j--;
          }
          if (j != k) {
            buffer.set(j, g);
            moved = true;
          }
        }
        if (moved) {
          int start = Integer.MAX_VALUE, stop = 0;
          for (int k = i; k < end; k++) {
            start = Math.min(start, buffer.get(k).start);
            stop = Math.max(stop, buffer.get(k).end);
          }
          for (int k = i; k < end; k++) {
            buffer.get(k).start = start;
            buffer.get(k).end = stop;
          }
        }
      }
      i = end + 1;
    }
  }
