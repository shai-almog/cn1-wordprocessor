  /** The OpenType tag of the USE script of a code point, or null. */
  static String script(int cp) {
    for (int k = 0; k < SCRIPTS.length; k += 3)
      if (cp >= (Integer) SCRIPTS[k + 1] && cp <= (Integer) SCRIPTS[k + 2]) return (String) SCRIPTS[k];
    return null;
  }

  /** USE category of a code point, as harfrust's hb_use_get_category. */
  static int category(int u) {
    if (u < 0 || u >= 921600) return O;
    int x1 = (CAT8.charAt(u >> 13) >> (((u >> 12) & 1) << 2)) & 15;
    int x2 = CAT8.charAt(113 + (x1 << 5) + ((u >> 7) & 31));
    int x3 = CAT16.charAt((x2 << 3) + ((u >> 4) & 7));
    int x4 = CAT8.charAt(625 + x3 + ((u >> 1) & 7));
    return CAT8.charAt(2953 + (x4 << 1) + (u & 1));
  }

  private static int[] decode(String s, int offset) {
    int[] a = new int[s.length()];
    for (int i = 0; i < a.length; i++) a[i] = s.charAt(i) - offset;
    return a;
  }

  private static boolean halant(OpenType.Glyph g) {
    return (g.cat == H || g.cat == HVM || g.cat == IS) && (g.flags & OpenType.LIGATED) == 0;
  }

  private static boolean postBase(int cat) {
    return cat >= FAbv && cat <= MPre || cat >= VAbv && cat <= VPst || cat >= VMAbv && cat <= VMPst
        || cat == VPre || cat == VMPre || cat >= FMAbv && cat <= FMPst;
  }

  /**
   * Categories and syllables (syllable serial << 4 | type) of every glyph, the rphf mask on each
   * syllable's first (up to) three glyphs, or just a Repha, and the topographical masks.
   */
  static void setup(List<OpenType.Glyph> buffer, int rphf, int[] forms) {
    for (var g : buffer) g.cat = category(g.cp);
    findSyllables(buffer);
    for (int s = 0, e; s < buffer.size(); s = e) {
      e = next(buffer, s);
      int limit = buffer.get(s).cat == R ? 1 : Math.min(3, e - s);
      for (int i = s; i < s + limit; i++) buffer.get(i).mask |= rphf;
    }
    int all = forms[0] | forms[1] | forms[2] | forms[3], lastStart = 0, last = -1;
    for (int s = 0, e; s < buffer.size(); s = e) {
      e = next(buffer, s);
      int type = buffer.get(s).syllable & 15;
      if (type == HIEROGLYPH || type == NON_CLUSTER) last = -1;
      else {
        boolean join = last == 3 || last == 0;
        if (join)
          for (int i = lastStart; i < s; i++)
            buffer.get(i).mask = buffer.get(i).mask & ~all | forms[last == 3 ? 2 : 1];
        last = join ? 3 : 0;
        for (int i = s; i < e; i++) buffer.get(i).mask = buffer.get(i).mask & ~all | forms[last];
      }
      lastStart = s;
    }
  }

  static int next(List<OpenType.Glyph> buffer, int s) {
    int syllable = buffer.get(s).syllable, e = s + 1;
    while (e < buffer.size() && buffer.get(e).syllable == syllable) e++;
    return e;
  }

  /** After rphf: the first substituted glyph among each syllable's rphf-masked ones is a Repha. */
  static void recordRphf(List<OpenType.Glyph> buffer, int rphf) {
    for (int s = 0, e; s < buffer.size(); s = e) {
      e = next(buffer, s);
      for (int i = s; i < e && (buffer.get(i).mask & rphf) != 0; i++)
        if ((buffer.get(i).flags & OpenType.SUBSTITUTED) != 0) {
          buffer.get(i).cat = R;
          break;
        }
    }
  }

  /** After pref: each syllable's first substituted glyph is a pre-base vowel. */
  static void recordPref(List<OpenType.Glyph> buffer) {
    for (int s = 0, e; s < buffer.size(); s = e) {
      e = next(buffer, s);
      for (int i = s; i < e; i++)
        if ((buffer.get(i).flags & OpenType.SUBSTITUTED) != 0) {
          buffer.get(i).cat = VPre;
          break;
        }
    }
  }

  /**
   * Inserts a dotted circle (glyph {@code dotted}, when the font has one) as the base of each
   * broken cluster, after a leading Repha, then moves each Repha after the base cluster and each
   * pre-base glyph before its halant group.
   */
  static void reorder(List<OpenType.Glyph> buffer, int dotted) {
    for (int s = 0, e; dotted != 0 && s < buffer.size(); s = e) {
      e = next(buffer, s);
      var first = buffer.get(s);
      if ((first.syllable & 15) != BROKEN) continue;
      int at = first.cat == R && e - s > 1 ? s + 1 : s;
      var circle = new OpenType.Glyph(dotted, 0x25cc, buffer.get(at).start, buffer.get(at).start,
          buffer.get(at).mask);
      circle.cat = B;
      circle.syllable = first.syllable;
      buffer.add(at, circle);
      e++;
    }
    for (int s = 0, e; s < buffer.size(); s = e) {
      e = next(buffer, s);
      int type = buffer.get(s).syllable & 15;
      if (type != VIRAMA_TERMINATED && type != SAKOT_TERMINATED && type != STANDARD
          && type != BROKEN) continue;
      boolean moved = false;
      if (buffer.get(s).cat == R && e - s > 1) {
        for (int i = s + 1; i < e; i++) {
          boolean post = postBase(buffer.get(i).cat) || halant(buffer.get(i));
          if (post || i == e - 1) {
            int to = post ? i - 1 : i;
            buffer.add(to, buffer.remove(s));
            moved = true;
            break;
          }
        }
      }
      int j = s;
      for (int i = s; i < e; i++) {
        var g = buffer.get(i);
        if (halant(g)) j = i + 1;
        else if ((g.cat == VPre || g.cat == VMPre) && g.components <= 1 && j < i) {
          buffer.add(j, buffer.remove(i));
          moved = true;
        }
      }
      if (moved) {
        int start = Integer.MAX_VALUE, end = 0;
        for (int k = s; k < e; k++) {
          start = Math.min(start, buffer.get(k).start);
          end = Math.max(end, buffer.get(k).end);
        }
        for (int k = s; k < e; k++) {
          buffer.get(k).start = start;
          buffer.get(k).end = end;
        }
      }
    }
  }

  private static boolean included(List<OpenType.Glyph> buffer, int i) {
    var g = buffer.get(i);
    if (g.cat == CGJ) return false;
    if (g.cat == ZWNJ)
      for (int k = i + 1; k < buffer.size(); k++)
        if (buffer.get(k).cat != CGJ) return !PdfShaping.mark(buffer.get(k).cp);
    return true;
  }

  /** harfrust's find_syllables: the Ragel scanner over the included glyphs. */
  static void findSyllables(List<OpenType.Glyph> buffer) {
    int[] at = new int[buffer.size() + 1];
    int n = 0;
    for (int i = 0; i < buffer.size(); i++) if (included(buffer, i)) at[n++] = i;
    at[n] = buffer.size();
    for (var g : buffer) g.syllable = 0;
    int[] serial = {1};
    int cs = 1, p = 0, pe = n, eof = n, ts = 0, te = 0, act = 0, trans = 0;
    resume:
    while (p != pe || p == eof) {
      if (FROM_STATE_ACTIONS[cs] == 3) ts = p;
      if (p == eof) {
        if (EOF_TRANS[cs] > 0) trans = EOF_TRANS[cs] - 1;
      } else {
        int c = buffer.get(at[p]).cat, keys = cs << 1, inds = INDEX_OFFSETS[cs];
        trans = INDEX_DEFAULTS[cs];
        if (c <= 56) {
          int ic = CHAR_CLASS[c];
          if (ic <= TRANS_KEYS[keys + 1] && ic >= TRANS_KEYS[keys])
            trans = INDICES[inds + ic - TRANS_KEYS[keys]];
        }
      }
      cs = COND_TARGS[trans];
      int type = -1;
      switch (COND_ACTIONS[trans]) {
        case 7: te = p + 1; break;
        case 16: te = p + 1; type = VIRAMA_TERMINATED; break;
        case 14: te = p + 1; type = SAKOT_TERMINATED; break;
        case 12: te = p + 1; type = STANDARD; break;
        case 20: te = p + 1; type = NUMBER_JOINER; break;
        case 18: te = p + 1; type = NUMERAL; break;
        case 10: te = p + 1; type = SYMBOL; break;
        case 25: te = p + 1; type = HIEROGLYPH; break;
        case 5: te = p + 1; type = BROKEN; break;
        case 4: te = p + 1; type = NON_CLUSTER; break;
        case 15: te = p; p--; type = VIRAMA_TERMINATED; break;
        case 13: te = p; p--; type = SAKOT_TERMINATED; break;
        case 11: te = p; p--; type = STANDARD; break;
        case 19: te = p; p--; type = NUMBER_JOINER; break;
        case 17: te = p; p--; type = NUMERAL; break;
        case 9: te = p; p--; type = SYMBOL; break;
        case 24: te = p; p--; type = HIEROGLYPH; break;
        case 21: te = p; p--; type = BROKEN; break;
        case 23: te = p; p--; type = NON_CLUSTER; break;
        case 1: p = te - 1; type = SYMBOL; break;
        case 22:
          if (act == 8) {
            p = te - 1;
            type = NON_CLUSTER;
          } else if (act == 9) {
            p = te - 1;
            type = BROKEN;
          }
          break;
        case 6: te = p + 1; act = 8; break;
        case 8: te = p + 1; act = 9; break;
        default: break;
      }
      if (type >= 0) found(buffer, at, ts, te, serial, type);
      if (p == eof) {
        if (cs >= 1) break resume;
      } else {
        if (TO_STATE_ACTIONS[cs] == 2) ts = 0;
        p++;
        continue resume;
      }
      break;
    }
  }

  private static void found(List<OpenType.Glyph> buffer, int[] at, int ts, int te, int[] serial,
      int type) {
    for (int i = at[ts]; i < at[te]; i++) buffer.get(i).syllable = serial[0] << 4 | type;
    if (++serial[0] == 16) serial[0] = 1;
  }

